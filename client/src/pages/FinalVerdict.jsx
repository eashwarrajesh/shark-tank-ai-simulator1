import React, { useState, useEffect } from 'react';

const INVESTOR_CONFIG = {
  money:   { emoji: '💰', name: 'Victor Cash',  color: '#f59e0b' },
  market:  { emoji: '🦈', name: 'Maya Street',  color: '#3b82f6' },
  product: { emoji: '🚀', name: 'Rex Doubt',    color: '#8b5cf6' },
};

const VERDICT_CONFIG = {
  INVEST:     { label: 'DEAL!',               icon: '🟢', color: '#10b981', bg: 'rgba(16,185,129,0.1)',  border: 'rgba(16,185,129,0.3)'  },
  INTERESTED: { label: 'INTERESTED — PROVE MORE', icon: '🟡', color: '#f59e0b', bg: 'rgba(245,158,11,0.1)',  border: 'rgba(245,158,11,0.3)'  },
  PASS:       { label: 'NO DEAL',             icon: '🔴', color: '#ef4444', bg: 'rgba(239,68,68,0.1)',   border: 'rgba(239,68,68,0.3)'   },
};

const SCORECARD_LABELS = {
  problemClarity:  'Problem Clarity',
  marketPotential: 'Market Potential',
  businessModel:   'Business Model',
  differentiation: 'Differentiation',
  productStrength: 'Product Strength',
  scalability:     'Scalability',
  founderResponse: 'Founder Response',
};

// ─── Animated counting number ─────────────────────────────────────────────────
function AnimatedScore({ target, color, size = 'md' }) {
  const [value, setValue] = useState(0);
  useEffect(() => {
    let cur = 0;
    const step = Math.max(1, Math.ceil(target / 40));
    const timer = setInterval(() => {
      cur = Math.min(cur + step, target);
      setValue(cur);
      if (cur >= target) clearInterval(timer);
    }, 30);
    return () => clearInterval(timer);
  }, [target]);
  return (
    <span className={`animated-score score-${size}`} style={{ color }} aria-label={`${value} out of 100`}>
      {value}
    </span>
  );
}

// ─── Score progress bar ───────────────────────────────────────────────────────
function ScoreBar({ label, score }) {
  const [width, setWidth] = useState(0);
  useEffect(() => {
    const t = setTimeout(() => setWidth(score), 200);
    return () => clearTimeout(t);
  }, [score]);
  const color = score >= 75 ? '#10b981' : score >= 50 ? '#f59e0b' : '#ef4444';
  return (
    <div className="scorecard-row" role="group" aria-label={`${label}: ${score} out of 100`}>
      <div className="scorecard-row-top">
        <span className="scorecard-label">{label}</span>
        <span className="scorecard-num" style={{ color }}>{score}</span>
      </div>
      <div className="scorecard-track" role="progressbar" aria-valuenow={score} aria-valuemin={0} aria-valuemax={100}>
        <div className="scorecard-fill" style={{ width: `${width}%`, backgroundColor: color, transition: 'width 0.9s ease' }} />
      </div>
    </div>
  );
}

// ─── Score comparison badge (Try Again flow) ──────────────────────────────────
function ScoreComparison({ oldScore, newScore }) {
  const diff = newScore - oldScore;
  const color = diff > 0 ? '#10b981' : diff < 0 ? '#ef4444' : '#f59e0b';
  const arrow = diff > 0 ? '↑' : diff < 0 ? '↓' : '→';
  return (
    <div className="score-comparison" aria-label={`Score changed from ${oldScore} to ${newScore}`}>
      <div className="sc-item">
        <span className="sc-label">First Attempt</span>
        <span className="sc-score sc-old">{oldScore}<small>/100</small></span>
      </div>
      <div className="sc-arrow" style={{ color }} aria-hidden="true">{arrow}</div>
      <div className="sc-item">
        <span className="sc-label">This Attempt</span>
        <span className="sc-score sc-new" style={{ color }}>{newScore}<small>/100</small></span>
      </div>
      <div className="sc-change" style={{ color }}>
        {diff > 0 ? `+${diff} improved` : diff < 0 ? `${diff} dropped` : 'same score'}
      </div>
    </div>
  );
}

// ─── Main component ───────────────────────────────────────────────────────────
export default function FinalVerdict({ verdict, pitchData, onPitchAgain, previousScore }) {
  const [copied, setCopied] = useState(false);

  const vc = VERDICT_CONFIG[verdict.verdict] || VERDICT_CONFIG.INTERESTED;
  const isDeal = verdict.deal === true;

  const buildReport = () => [
    `🦈 SHARK TANK AI — INVESTOR REPORT`,
    `Startup: ${pitchData.startupName}`,
    `Pitch: ${pitchData.oneLiner}`,
    ``,
    `━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`,
    `SCORE: ${verdict.overallScore}/100   VERDICT: ${vc.label}`,
    `Money: ${verdict.money}/10   Customer: ${verdict.customer}/10   Risk: ${verdict.risk}/10`,
    `━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`,
    ``,
    `WEAKEST ANSWER`,
    verdict.weakest_answer || '—',
    ``,
    `STRONGER VERSION`,
    verdict.better_version || '—',
    ``,
    `3 FIXES`,
    ...(verdict.fixes || []).map((f, i) => `${i + 1}. ${f}`),
    verdict.deal && verdict.offer ? `\nOFFER: ${verdict.offer}` : '',
    ``,
    `Generated by Shark Tank AI`,
  ].filter((l) => l !== undefined).join('\n');

  const handleCopy = async () => {
    try { await navigator.clipboard.writeText(buildReport()); }
    catch { const ta = document.createElement('textarea'); ta.value = buildReport(); document.body.appendChild(ta); ta.select(); document.execCommand('copy'); document.body.removeChild(ta); }
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <main className="verdict-page">

      {/* ── DEAL / NO DEAL hero ── */}
      <section className={`deal-hero ${isDeal ? 'deal-hero--deal' : 'deal-hero--nodeal'}`} aria-labelledby="verdict-heading">
        <div className="badge">FINAL VERDICT</div>
        <h1 id="verdict-heading" className="verdict-startup-name">{pitchData.startupName}</h1>

        <div className="verdict-score-circle" style={{ borderColor: vc.color }}>
          <div className="verdict-score-inner">
            <AnimatedScore target={verdict.overallScore} color={vc.color} size="xl" />
            <span className="verdict-score-denom" style={{ color: vc.color }}>/100</span>
            <span className="verdict-score-label">Investment Score</span>
          </div>
        </div>

        <div className="verdict-badge" style={{ color: vc.color, background: vc.bg, borderColor: vc.border }} role="status">
          <span aria-hidden="true">{vc.icon}</span> {vc.label}
        </div>

        {isDeal && verdict.offer && (
          <div className="deal-offer" role="note" aria-label="Shark offer">
            <span aria-hidden="true">🤝</span> {verdict.offer}
          </div>
        )}

        {/* Score comparison if this is a retry */}
        {previousScore != null && (
          <ScoreComparison oldScore={previousScore} newScore={verdict.overallScore} />
        )}
      </section>

      {/* ── Individual investor scores ── */}
      <section className="verdict-section" aria-labelledby="shark-scores-heading">
        <h2 id="shark-scores-heading" className="section-title">Shark Scores</h2>
        <div className="shark-scores-grid">
          {[
            { key: 'money',   score: verdict.money,    label: 'Money' },
            { key: 'market',  score: verdict.customer,  label: 'Customer' },
            { key: 'product', score: verdict.risk,      label: 'Risk' },
          ].map(({ key, score, label }) => {
            const inv = INVESTOR_CONFIG[key];
            const s = Math.max(1, Math.min(10, score || 1));
            const color = s >= 7 ? '#10b981' : s >= 5 ? '#f59e0b' : '#ef4444';
            return (
              <div key={key} className="shark-score-card" style={{ '--card-color': inv.color }}>
                <span className="shark-score-emoji" aria-hidden="true">{inv.emoji}</span>
                <span className="shark-score-name">{inv.name}</span>
                <span className="shark-score-label" style={{ color: inv.color }}>{label}</span>
                <span className="shark-score-num" style={{ color }}>{s}<small>/10</small></span>
              </div>
            );
          })}
        </div>
      </section>

      {/* ── Weakest answer + better version ── */}
      {verdict.weakest_answer && (
        <section className="verdict-section" aria-labelledby="hardtruth-heading">
          <div className="hard-truth-card">
            <h2 id="hardtruth-heading" className="hard-truth-title">
              <span aria-hidden="true">⚡</span> The Hard Truth
            </h2>
            {verdict.weakness_reason && (
              <p className="weakness-reason">{verdict.weakness_reason}</p>
            )}
            <div className="before-after">
              <div className="ba-block ba-before">
                <span className="ba-tag">
                  {verdict.weakest_question
                    ? `Q: "${verdict.weakest_question.slice(0, 80)}${verdict.weakest_question.length > 80 ? '…' : ''}"`
                    : 'What you said'}
                </span>
                <p className="ba-text">"{verdict.weakest_answer}"</p>
              </div>
              <div className="ba-arrow" aria-hidden="true">→</div>
              <div className="ba-block ba-after">
                <span className="ba-tag">Stronger version — same question</span>
                <p className="ba-text">"{verdict.better_version}"</p>
              </div>
            </div>
          </div>
        </section>
      )}

      {/* ── 3-Step Fixes ── */}
      {verdict.fixes && verdict.fixes.length > 0 && (
        <section className="verdict-section rescue-section" aria-labelledby="rescue-heading">
          <h2 id="rescue-heading" className="section-title rescue-title">
            <span aria-hidden="true">🛠</span> 3-Step Pitch Rescue
          </h2>
          <p className="rescue-sub">Specific to your pitch. Fix these before you pitch again.</p>
          <ol className="rescue-list">
            {verdict.fixes.map((step, i) => (
              <li key={i} className="rescue-item">
                <div className="rescue-num" aria-hidden="true">{i + 1}</div>
                <p className="rescue-text">{step}</p>
              </li>
            ))}
          </ol>
        </section>
      )}

      {/* ── Full scorecard ── */}
      <section className="verdict-section" aria-labelledby="scorecard-heading">
        <h2 id="scorecard-heading" className="section-title">Pitch Scorecard</h2>
        <div className="scorecard-grid">
          {verdict.scorecard && Object.entries(verdict.scorecard).map(([key, score]) => (
            <ScoreBar key={key} label={SCORECARD_LABELS[key] || key} score={score} />
          ))}
        </div>
      </section>

      {/* ── Investor verdicts ── */}
      <section className="verdict-section" aria-labelledby="investor-verdicts-heading">
        <h2 id="investor-verdicts-heading" className="section-title">Investor Verdicts</h2>
        <div className="investor-verdicts-grid">
          {Object.entries(INVESTOR_CONFIG).map(([key, inv]) => {
            const iv = verdict.investorVerdicts?.[key];
            if (!iv) return null;
            const ivc = VERDICT_CONFIG[iv.verdict?.toUpperCase()] || VERDICT_CONFIG.INTERESTED;
            return (
              <article key={key} className="investor-verdict-card" style={{ '--card-color': inv.color }}>
                <div className="ivc-header">
                  <span className="ivc-emoji" aria-hidden="true">{inv.emoji}</span>
                  <div>
                    <h3 className="ivc-name">{inv.name}</h3>
                    <span className="ivc-verdict" style={{ color: ivc.color, background: ivc.bg, borderColor: ivc.border }}>
                      {ivc.icon} {iv.verdict}
                    </span>
                  </div>
                </div>
                <p className="ivc-reason">{iv.reason}</p>
              </article>
            );
          })}
        </div>
      </section>

      {/* ── Actions ── */}
      <section className="verdict-actions" aria-label="Next steps">
        <button className="btn btn-primary btn-lg" onClick={onPitchAgain} type="button">
          🔄 Try Again — Improve Your Pitch
        </button>
        <button
          className="btn btn-secondary btn-lg"
          onClick={handleCopy}
          type="button"
          aria-live="polite"
        >
          {copied ? '✅ Copied!' : '📋 Copy Investor Report'}
        </button>
      </section>
    </main>
  );
}
